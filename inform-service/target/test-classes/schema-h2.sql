CREATE TABLE IF NOT EXISTS informs (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       user_id BIGINT NOT NULL,
                                       type VARCHAR(50) NOT NULL,
    content TEXT,
    related_id VARCHAR(255),
    from_user_id BIGINT,
    is_read BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP
    );

CREATE INDEX IF NOT EXISTS idx_user_id ON informs (user_id);
CREATE INDEX IF NOT EXISTS idx_user_read ON informs (user_id, is_read);
CREATE INDEX IF NOT EXISTS idx_created_at ON informs (created_at);
CREATE INDEX IF NOT EXISTS idx_from_user_id ON informs (from_user_id);
CREATE INDEX IF NOT EXISTS idx_type ON informs (type);